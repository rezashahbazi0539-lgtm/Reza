export function tr(key, params) {
  let value = key.split('.').reduce((obj, k) => obj?.[k], t);
  if (typeof value === 'string' && params) {
    Object.keys(params).forEach(k => {
      value = value.replace(`{${k}}`, params[k]);
    });
  }
  return value || key;
}
